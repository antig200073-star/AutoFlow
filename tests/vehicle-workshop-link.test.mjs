import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const customer = '00000000-0000-0000-0000-000000000001';
const stranger = '00000000-0000-0000-0000-000000000002';
const workshop = '00000000-0000-0000-0000-000000000003';
const blocked = '00000000-0000-0000-0000-000000000004';

test('vínculo de O.S. com veículo do cliente sem duplicar cadastros (PostgreSQL)', async t => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth; create schema private;
    create table auth.users(id uuid primary key);
    insert into auth.users values('${customer}'),('${stranger}'),('${workshop}'),('${blocked}');
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema public,auth,private to authenticated,anon;
    create table tb_cli(id_cliente bigint generated by default as identity primary key,nome text,auth_user_id uuid references auth.users);
    create table tb_veiculo(id_veiculo bigint generated by default as identity primary key,cliente_id bigint references tb_cli,placa text,modelo text,excluido_em timestamptz);
    create table oficinas(id bigint primary key,user_id uuid,status text);
    create table ordens_servico(id bigint generated by default as identity primary key,oficina_id bigint references oficinas,cliente_id bigint references tb_cli,veiculo_id bigint references tb_veiculo,status text,descricao_problema text);
    insert into tb_cli values(1,'Cliente com conta','${customer}'),(2,'Outra pessoa','${stranger}'),(23,'Cliente com conta',null);
    insert into tb_veiculo values(14,1,'ABC1D23','Veículo do cliente',null),(15,23,'ABC1D23','Cópia da oficina',null),(16,2,'DEF4G56','Veículo alheio',null);
    insert into oficinas values(3,'${workshop}','aprovada'),(4,'${blocked}','bloqueada');
    insert into ordens_servico values(5,3,23,15,'em_manutencao','Teste do defeito relatado');
    select setval(pg_get_serial_sequence('tb_cli','id_cliente'),100);
    select setval(pg_get_serial_sequence('tb_veiculo','id_veiculo'),100);
    select setval(pg_get_serial_sequence('ordens_servico','id'),100);
    alter table ordens_servico enable row level security;
    create policy order_read on ordens_servico for select to authenticated using(
      cliente_id in(select id_cliente from tb_cli where auth_user_id=auth.uid())
      or oficina_id in(select id from oficinas where user_id=auth.uid() and status='aprovada'));
    grant select on tb_cli,oficinas,ordens_servico to authenticated;
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20261021121433_vehicle_workshop_link.sql',import.meta.url),'utf8'));
  await db.exec(`create function public.create_workshop_order(p_plate text,p_model text,p_client text,p_problem text,p_status text default 'aguardando')
    returns bigint language sql security invoker set search_path='' as $$select private.create_workshop_order(p_plate,p_model,p_client,p_problem,p_status)$$;
    revoke all on function private.create_workshop_order(text,text,text,text,text),public.create_workshop_order(text,text,text,text,text) from public,anon;
    grant execute on function private.create_workshop_order(text,text,text,text,text),public.create_workshop_order(text,text,text,text,text) to authenticated;`);
  async function asUser(uid, action, role='authenticated') {
    await db.exec(`set role ${role}; select set_config('request.jwt.claim.sub','${uid}',false)`);
    try { return await action(); } finally { await db.exec('reset role'); }
  }
  const issue = id => db.query('select issue_vehicle_workshop_link($1) as link',[id]).then(r => r.rows[0].link);
  const createLinked = (code,plate='ABC1D23') => db.query("select create_workshop_order_with_link($1,'Modelo digitado','Cliente com conta','Revisão','em_manutencao',$2) as id",[plate,code]).then(r => r.rows[0].id);
  const createUnlinked = (plate='ABC1D23',name='Cliente com conta') => db.query("select create_workshop_order($1,'Modelo',$2,'Revisão','em_analise') as id",[plate,name]).then(r => r.rows[0].id);
  let link;
  await t.test('reproduz O.S. invisível por duplicação e bloqueia nova duplicata mesmo com atendimento legado', async () => {
    await asUser(customer, async()=>assert.equal((await db.query('select id from ordens_servico where id=5')).rows.length,0));
    await asUser(workshop, ()=>assert.rejects(createUnlinked(),/código/));
    assert.equal((await db.query('select count(*)::int as total from tb_cli')).rows[0].total,3);
    assert.equal((await db.query('select count(*)::int as total from tb_veiculo')).rows[0].total,3);
  });
  await t.test('cliente só emite código do próprio veículo ativo; tokens não podem ser listados pela API', async () => {
    await asUser(stranger, ()=>assert.rejects(issue(14),/não disponível/));
    await asUser('', ()=>assert.rejects(issue(14),/permission denied/),'anon');
    await asUser(customer, async()=>{
      await assert.rejects(db.query('select * from private.vehicle_workshop_links'),/permission denied/);
      link=await issue(14); assert.match(link.code,/^[a-f0-9-]{36}$/);
      assert.ok(new Date(link.expires_at)>new Date());
    });
  });
  await t.test('oficina bloqueada, placa diferente e token inexistente não consomem autorização', async () => {
    await asUser(blocked,()=>assert.rejects(createLinked(link.code),/sem aprovação/));
    await asUser(workshop,async()=>{
      await assert.rejects(createLinked(link.code,'DEF4G56'),/não corresponde/);
      await assert.rejects(createLinked('00000000-0000-0000-0000-000000000099'),/inválido/);
    });
    assert.equal((await db.query('select used_at from private.vehicle_workshop_links')).rows[0].used_at,null);
  });
  await t.test('regenerar e expirar invalidam o código anterior',async()=>{
    const old=link.code;link=await asUser(customer,()=>issue(14));
    await asUser(workshop,()=>assert.rejects(createLinked(old),/inválido/));
    await db.exec("update private.vehicle_workshop_links set expires_at=now()-interval '1 second'");
    await asUser(workshop,()=>assert.rejects(createLinked(link.code),/expirado/));
    link=await asUser(customer,()=>issue(14));
  });
  let linkedId;
  await t.test('ordem usa cliente e veículo originais, aparece ao cliente e mantém a ordem antiga intocada',async()=>{
    linkedId=await asUser(workshop,()=>createLinked(link.code));
    const row=(await db.query('select * from ordens_servico where id=$1',[linkedId])).rows[0];
    assert.equal(row.cliente_id,1);assert.equal(row.veiculo_id,14);assert.equal(row.status,'em_manutencao');
    await asUser(customer,async()=>assert.equal((await db.query('select id from ordens_servico where id=$1',[linkedId])).rows.length,1));
    await asUser(stranger,async()=>assert.equal((await db.query('select id from ordens_servico where id=$1',[linkedId])).rows.length,0));
    assert.equal((await db.query('select cliente_id from ordens_servico where id=5')).rows[0].cliente_id,23);
    assert.equal((await db.query('select count(*)::int as total from tb_cli')).rows[0].total,3);
    assert.equal((await db.query('select count(*)::int as total from tb_veiculo')).rows[0].total,3);
  });
  await t.test('código é de uso único e a oficina reaproveita vínculo confirmado no próximo atendimento',async()=>{
    await asUser(workshop,()=>assert.rejects(createLinked(link.code),/já utilizado/));
    const next=await asUser(workshop,()=>createUnlinked());
    const row=(await db.query('select cliente_id,veiculo_id from ordens_servico where id=$1',[next])).rows[0];
    assert.deepEqual(row,{cliente_id:1,veiculo_id:14});
  });
  await t.test('cadastro avulso de placa desconhecida continua disponível',async()=>{
    const id=await asUser(workshop,()=>createUnlinked('XYZ9J87','Cliente avulso'));
    const row=(await db.query('select c.auth_user_id from ordens_servico os join tb_cli c on c.id_cliente=os.cliente_id where os.id=$1',[id])).rows[0];
    assert.equal(row.auth_user_id,null);
  });
  await t.test('reparo pontual proposto torna a O.S. existente visível sem mudar o status',async()=>{
    // Somente no banco local: a correção de produção exige aprovação explícita.
    await db.query('update ordens_servico set cliente_id=1,veiculo_id=14 where id=5 and cliente_id=23 and veiculo_id=15');
    await asUser(customer,async()=>{
      const row=(await db.query('select id,status,veiculo_id from ordens_servico where id=5')).rows[0];
      assert.deepEqual(row,{id:5,status:'em_manutencao',veiculo_id:14});
    });
  });
});
