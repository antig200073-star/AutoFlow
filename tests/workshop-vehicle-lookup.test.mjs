import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('consulta por placa respeita o vínculo da oficina e não altera cadastros', async t => {
  const db = new PGlite(); t.after(() => db.close());
  const owner='00000000-0000-0000-0000-000000000001';
  const workshop='00000000-0000-0000-0000-000000000002';
  const other='00000000-0000-0000-0000-000000000003';
  const blocked='00000000-0000-0000-0000-000000000004';
  await db.exec(`create role anon; create role authenticated; create schema auth; create schema private;
    create table auth.users(id uuid primary key);
    insert into auth.users values('${owner}'),('${workshop}'),('${other}'),('${blocked}');
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema public,auth,private to authenticated,anon;
    create table tb_cli(id_cliente bigint primary key,nome text,auth_user_id uuid);
    create table tb_veiculo(id_veiculo bigint primary key,cliente_id bigint references tb_cli,placa text,marca text,modelo text,ano_do_modelo numeric,excluido_em timestamptz);
    create table oficinas(id bigint primary key,user_id uuid,status text);
    create table ordens_servico(id bigint generated by default as identity primary key,oficina_id bigint references oficinas,cliente_id bigint references tb_cli,veiculo_id bigint references tb_veiculo,status text,descricao_problema text);
    insert into oficinas values(1,'${workshop}','aprovada'),(2,'${other}','aprovada'),(3,'${blocked}','bloqueada');
    insert into tb_cli values(1,'Cliente A','${owner}'),(2,'Cliente avulso',null);
    insert into tb_veiculo values(1,1,'ABC1234','Chevrolet','Celta',2007,null),
      (2,1,'DEF4G56','Honda','Civic',2020,null),(3,1,'GHI7J89','Ford','Ka',2017,now()),
      (4,2,'JKL1234',null,'Modelo antigo sem ano',null,null);
    insert into ordens_servico(oficina_id,cliente_id,veiculo_id,status) values(1,1,1,'entregue'),(2,2,4,'entregue');
  `);
  for (const file of ['20261021121433_vehicle_workshop_link.sql','20261023154200_workshop_vehicle_lookup.sql']) {
    await db.exec(await readFile(new URL(`../supabase/migrations/${file}`,import.meta.url),'utf8'));
  }
  async function asUser(uid,fn,role='authenticated') {
    await db.exec(`set role ${role}; select set_config('request.jwt.claim.sub','${uid}',false)`);
    try {return await fn();} finally {await db.exec('reset role');}
  }
  const lookup=(plate,code=null)=>db.query('select lookup_workshop_vehicle($1,$2) as data',[plate,code]).then(r=>r.rows[0].data);
  const issue=()=>asUser(owner,()=>db.query('select issue_vehicle_workshop_link(2) as data').then(r=>r.rows[0].data));
  await t.test('placa normalizada de atendimento anterior preenche marca, modelo, ano e nome',async()=>{
    const data=await asUser(workshop,()=>lookup('abc-1234'));
    assert.deepEqual(data,{status:'found',plate:'ABC1234',brand:'Chevrolet',model:'Celta',year:2007,client_name:'Cliente A'});
  });
  await t.test('oficina sem vínculo não recebe nome nem dados do veículo',async()=>{
    assert.deepEqual(await asUser(other,()=>lookup('ABC1234')),{status:'needs_link'});
    assert.deepEqual(await asUser(workshop,()=>lookup('DEF4G56')),{status:'needs_link'});
    assert.deepEqual(await asUser(workshop,()=>lookup('JKL1234')),{status:'needs_review'});
  });
  await t.test('oficina bloqueada, cliente sem oficina, anônimo e placa inválida são recusados',async()=>{
    await asUser(blocked,()=>assert.rejects(lookup('ABC1234'),/sem aprovação/));
    await asUser(owner,()=>assert.rejects(lookup('ABC1234'),/sem aprovação/));
    await asUser('',()=>assert.rejects(lookup('ABC1234'),/permission denied/),'anon');
    await asUser(workshop,()=>assert.rejects(lookup('ABC'),/placa válida/));
  });
  let link;
  await t.test('prévia com código válido não consome autorização nem cria clientes, veículos ou O.S.',async()=>{
    link=await issue();
    for(let i=0;i<2;i++) {
      const data=await asUser(workshop,()=>lookup('DEF4G56',link.code));
      assert.equal(data.client_name,'Cliente A'); assert.equal(data.year,2020);
    }
    assert.equal((await db.query('select used_at from private.vehicle_workshop_links')).rows[0].used_at,null);
    assert.deepEqual((await db.query('select (select count(*)::int from tb_cli) as clients,(select count(*)::int from tb_veiculo) as vehicles,(select count(*)::int from ordens_servico) as orders')).rows[0],{clients:2,vehicles:4,orders:2});
  });
  await t.test('código de outra placa, malformado e expirado não preenchem dados',async()=>{
    for(const [plate,code] of [['ABC1234',link.code],['DEF4G56','inválido']])
      assert.deepEqual(await asUser(workshop,()=>lookup(plate,code)),{status:'invalid_link'});
    await db.exec("update private.vehicle_workshop_links set expires_at=now()-interval '1 second'");
    assert.deepEqual(await asUser(workshop,()=>lookup('DEF4G56',link.code)),{status:'invalid_link'});
    link=await issue();
  });
  await t.test('código consultado ainda abre a O.S.; depois disso basta a placa',async()=>{
    await asUser(workshop,()=>db.query("select create_workshop_order_with_link('DEF4G56','Honda Civic 2020','Cliente A','Revisão','em_analise',$1)",[link.code]));
    assert.deepEqual(await asUser(workshop,()=>lookup('DEF4G56',link.code)),{status:'invalid_link'});
    assert.equal((await asUser(workshop,()=>lookup('DEF4G56'))).client_name,'Cliente A');
  });
  await t.test('removido e desconhecido têm mensagens distintas; cadastro incompleto não inventa ano',async()=>{
    assert.deepEqual(await asUser(workshop,()=>lookup('GHI7J89')),{status:'removed'});
    assert.deepEqual(await asUser(workshop,()=>lookup('XYZ9J87')),{status:'not_found'});
    const old=await asUser(other,()=>lookup('JKL1234'));
    assert.equal(old.year,null);assert.equal(old.brand,null);assert.equal(old.client_name,'Cliente avulso');
  });
});
