-- AutoFlow: chat individual por ordem de serviço.
-- Executada no Supabase AutoFlow em 26/10/2026.
-- Aplicação repetida segura para tabelas já existentes.
create table if not exists public.chat_conversas (
  id bigint generated by default as identity primary key,
  ordem_servico_id bigint not null unique references public.ordens_servico(id) on delete cascade,
  criada_por uuid not null default auth.uid() references auth.users(id),
  criada_em timestamptz not null default now()
);
create table if not exists public.chat_mensagens (
  id bigint generated by default as identity primary key,
  conversa_id bigint not null references public.chat_conversas(id) on delete cascade,
  remetente_id uuid not null references auth.users(id),
  conteudo text not null check (length(btrim(conteudo)) between 1 and 2000),
  criada_em timestamptz not null default now()
);
create table if not exists public.chat_leituras (
  conversa_id bigint not null references public.chat_conversas(id) on delete cascade,
  usuario_id uuid not null references auth.users(id),
  visto_em timestamptz not null default now(),
  primary key(conversa_id, usuario_id)
);
create index if not exists idx_chat_mensagens_conversa_data on public.chat_mensagens(conversa_id, criada_em);
alter table public.chat_conversas enable row level security;
alter table public.chat_mensagens enable row level security;
alter table public.chat_leituras enable row level security;
grant select,insert on public.chat_conversas to authenticated;
grant select,insert on public.chat_mensagens to authenticated;
grant select,insert,update on public.chat_leituras to authenticated;
drop policy if exists chat_conversas_ler on public.chat_conversas;
create policy chat_conversas_ler on public.chat_conversas for select to authenticated
using (exists (select 1 from public.ordens_servico os where os.id=ordem_servico_id
and (private.owns_client(os.cliente_id) or private.owns_active_workshop(os.oficina_id))));
drop policy if exists chat_conversas_criar on public.chat_conversas;
create policy chat_conversas_criar on public.chat_conversas for insert to authenticated
with check (criada_por=(select auth.uid()) and exists (select 1 from public.ordens_servico os
where os.id=ordem_servico_id and
(private.owns_client(os.cliente_id) or private.owns_active_workshop(os.oficina_id))));
drop policy if exists chat_mensagens_ler on public.chat_mensagens;
create policy chat_mensagens_ler on public.chat_mensagens for select to authenticated
using (exists (select 1 from public.chat_conversas c where c.id=conversa_id));
drop policy if exists chat_mensagens_enviar on public.chat_mensagens;
create policy chat_mensagens_enviar on public.chat_mensagens for insert to authenticated
with check (remetente_id=(select auth.uid()) and exists
(select 1 from public.chat_conversas c where c.id=conversa_id));
drop policy if exists chat_leituras_ler on public.chat_leituras;
create policy chat_leituras_ler on public.chat_leituras for select to authenticated
using (usuario_id=(select auth.uid()) and exists
(select 1 from public.chat_conversas c where c.id=conversa_id));
drop policy if exists chat_leituras_criar on public.chat_leituras;
create policy chat_leituras_criar on public.chat_leituras for insert to authenticated
with check (usuario_id=(select auth.uid()) and exists
(select 1 from public.chat_conversas c where c.id=conversa_id));
drop policy if exists chat_leituras_atualizar on public.chat_leituras;
create policy chat_leituras_atualizar on public.chat_leituras for update to authenticated
using (usuario_id=(select auth.uid()) and exists
(select 1 from public.chat_conversas c where c.id=conversa_id))
with check (usuario_id=(select auth.uid()) and exists
(select 1 from public.chat_conversas c where c.id=conversa_id));
